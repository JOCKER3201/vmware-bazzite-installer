// Static contents of files generated into the extension:
// sysext metadata, systemd units, factory /etc/vmware,
// fallback SELinux contexts for mkfs.erofs.
//
// The contents are based on the proven layout of the AUR vmware-workstation
// package (github.com/archlinux/aur, vmware-workstation branch) and on the
// practice of the fedora-sysexts and Flatcar projects (the Upholds= pattern
// for sysexts).

/// Extension metadata — the file name must match the image name
/// (vmware.raw → extension-release.vmware). ID=_any: a deliberate choice
/// of the fedora-sysexts ecosystem, consistent with Universal Blue/Bazzite.
pub const EXTENSION_RELEASE: &str = "\
ID=_any
ARCHITECTURE=x86-64
SYSEXT_SCOPE=system
EXTENSION_RELOAD_MANAGER=1
";

/// Kernel module loading. We deliberately do NOT use modules-load.d —
/// systemd-modules-load.service has no guaranteed ordering relative to
/// systemd-sysext.service and may start before the extension is merged.
/// %v = version of the running kernel (uname -r): after a kernel update
/// the unit turns itself off via the condition instead of spewing errors.
pub const UNIT_MODULES: &str = "\
[Unit]
Description=Load VMware kernel modules (vmw_vmci, vmmon, vmnet)
ConditionPathExists=/usr/lib/modules/%v/misc/vmmon.ko

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=-/usr/sbin/modprobe vmw_vmci
ExecStart=-/usr/sbin/modprobe vmmon
ExecStart=-/usr/sbin/modprobe vmnet

[Install]
WantedBy=multi-user.target
";

pub const UNIT_NETWORKS_CONFIGURATION: &str = "\
[Unit]
Description=Generate the default VMware network configuration (/etc/vmware/networking)
ConditionPathExists=!/etc/vmware/networking
After=systemd-tmpfiles-setup.service

[Service]
Type=oneshot
RemainAfterExit=yes
UMask=0077
ExecStart=/usr/bin/vmware-networks --postinstall vmware-player,0,1
";

pub const UNIT_NETWORKS: &str = "\
[Unit]
Description=VMware virtual network services (vmnet)
Wants=vmware-networks-configuration.service
After=vmware-networks-configuration.service systemd-tmpfiles-setup.service network-pre.target

[Service]
Type=forking
ExecStartPre=-/usr/sbin/modprobe vmnet
ExecStart=/usr/bin/vmware-networks --start
ExecStop=/usr/bin/vmware-networks --stop

[Install]
WantedBy=multi-user.target
";

pub const UNIT_USBARBITRATOR: &str = "\
[Unit]
Description=VMware USB arbitrator (USB device passthrough to virtual machines)
After=systemd-tmpfiles-setup.service

[Service]
ExecStartPre=-/usr/sbin/modprobe vmmon
ExecStart=/usr/lib/vmware/bin/vmware-usbarbitrator -f

[Install]
WantedBy=multi-user.target
";

/// Service autostart after the extension is merged — the Flatcar/fedora-sysexts
/// pattern: a drop-in on multi-user.target with Upholds= instead of systemctl
/// enable (enable symlinks cannot be shipped in a sysext, as they live in /etc).
pub const UPHOLDS_DROPIN: &str = "\
[Unit]
Upholds=vmware-modules.service
Upholds=vmware-networks.service
Upholds=vmware-usbarbitrator.service
";

